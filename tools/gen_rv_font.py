"""Ravel's screen fonts as a C header: Space Grotesk (SIL OFL 1.1, assets/fonts; a variable font,
set at a weight per role),
anti-aliased at 2 bits per pixel, each glyph cropped to its ink. Three roles: T (labels, the
footer), XS (lists, names), B (values, titles, readouts).

  gen_rv_font.py OUT.h
"""
import sys
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

FONTS = Path(__file__).resolve().parents[1] / "assets" / "fonts"
# Ravel's screen is set in capitals: the fonts stop at '_' (lower case falls back to capitals)
ROLES = [("T", "SpaceGrotesk-Variable.ttf", 9, 32, 95, 600),
         ("XS", "SpaceGrotesk-Variable.ttf", 11, 32, 95, 600),
         ("B", "SpaceGrotesk-Variable.ttf", 14, 32, 95, 640)]
KEEP = {}
GAMMA = 0.6     # thin strokes at small sizes get more of their ink (the panel's 2-bit levels drop faint ones)


def render(ttf, px, first, last, keep, wght=None):
    font = ImageFont.truetype(str(FONTS / ttf), px)
    if wght:
        font.set_variation_by_axes([wght])
    asc, desc = font.getmetrics()
    top = max(0, font.getbbox("A8|(")[1] - 1)
    h = asc + desc - top
    glyphs = []
    for c in range(first, last + 1):
        ch = chr(c)
        feat = ["tnum"] if ch.isdigit() else None     # figures share one width (values don't jitter); letters keep their own
        adv = int(round(font.getlength(ch, features=feat)))
        if keep and ch not in keep:
            glyphs.append((0, 0, 0, []))
            continue
        w = adv + 6
        img = Image.new("L", (w, asc + desc), 0)
        ImageDraw.Draw(img).text((3, 0), ch, font=font, fill=255, features=feat)
        img = img.crop((0, top, w, top + h))
        px_ = list(img.tobytes())
        cols = [x for x in range(w) if any(px_[y * w + x] >= 32 for y in range(h))]
        if not cols:
            glyphs.append((adv, 0, 0, []))
            continue
        x0, x1 = cols[0], cols[-1] + 1
        g = [min(3, int(round(3.0 * (px_[y * w + x] / 255.0) ** GAMMA))) for y in range(h) for x in range(x0, x1)]
        glyphs.append((adv, x0 - 3, x1 - x0, g))
    return h, glyphs


def main(out):
    lines = ["/* generated by tools/gen_rv_font.py: Space Grotesk, 2 bits per pixel */",
             "#pragma once", "#include <stdint.h>", ""]
    total = 0
    for name, ttf, px, first, last, wght in ROLES:
        h, glyphs = render(ttf, px, first, last, KEEP.get(name), wght)
        data, offs = [], []
        for adv, bx, bw, g in glyphs:
            offs.append(len(data))
            bpr = (bw + 3) // 4
            for y in range(h):
                row = g[y * bw:(y + 1) * bw] + [0, 0, 0]
                for x in range(0, bpr * 4, 4):
                    data.append((row[x] << 6) | (row[x + 1] << 4) | (row[x + 2] << 2) | row[x + 3])
        total += len(data) + 4 * len(glyphs)
        lines.append(f"static const uint8_t FONT_{name}_DATA[{max(1, len(data))}] = {{")
        for i in range(0, len(data), 24):
            lines.append("    " + ", ".join(f"0x{b:02x}" for b in data[i:i + 24]) + ",")
        lines.append("};")
        lines.append(f"static const uint16_t FONT_{name}_OFF[{len(offs)}] = {{" + ", ".join(map(str, offs)) + "};")
        lines.append(f"static const uint8_t FONT_{name}_ADV[{len(glyphs)}] = {{" + ", ".join(str(a) for a, _, _, _ in glyphs) + "};")
        lines.append(f"static const int8_t FONT_{name}_BX[{len(glyphs)}] = {{" + ", ".join(str(b) for _, b, _, _ in glyphs) + "};")
        lines.append(f"static const uint8_t FONT_{name}_BW[{len(glyphs)}] = {{" + ", ".join(str(w) for _, _, w, _ in glyphs) + "};")
        lines.append(f"static const rv_font_t FONT_{name} = {{ {h}, {first}, {last}, FONT_{name}_ADV, FONT_{name}_BX, FONT_{name}_BW, FONT_{name}_OFF, FONT_{name}_DATA }};")
        lines.append("")
    print(f"fonts: {total} B")
    Path(out).write_text("\n".join(lines))


if __name__ == "__main__":
    main(sys.argv[1])
