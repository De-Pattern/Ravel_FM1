"""Ravel's screen fonts as a C header: a runic stroke alphabet of our own (tools/runic_glyphs.py),
straight strokes drawn at 8x and brought down to the screen at 4 bits per pixel. Three roles: T
(labels, the footer), XS (lists, names), B (values, titles, readouts).

  gen_rv_font.py OUT.h
"""
import sys
from pathlib import Path
from PIL import Image, ImageDraw
sys.path.insert(0, str(Path(__file__).resolve().parent))
from runic_glyphs import G

# role, cap height (px), stroke (px), letter gap (px), line height (px)
ROLES = [("T", 6.2, 0.95, 1.4, 12), ("XS", 7.6, 1.1, 1.6, 14), ("B", 9.8, 1.35, 1.5, 18)]
SS = 8
GAMMA = 0.8


def render(cap, stroke, gap, lh):
    s = cap / 6.0
    top = 1.6 if lh < 16 else 2.2
    glyphs = []
    for c in range(32, 96):
        ch = chr(c)
        if ch not in G:
            glyphs.append((0, 0, 0, []))
            continue
        gw, lines = G[ch]
        w = int(gw * s + stroke + 4)
        img = Image.new("L", (w * SS, lh * SS), 0)
        d = ImageDraw.Draw(img)
        lw = max(1, int(round(stroke * SS)))
        for pl in lines:
            pts = [((1.5 + stroke / 2 + x * s) * SS, (top + y * s) * SS) for x, y in pl]
            d.line(pts, fill=255, width=lw, joint="curve")
            for p in (pts[0], pts[-1]):               # square-ish ends, a touch rounded
                r = lw / 2
                d.ellipse([p[0] - r, p[1] - r, p[0] + r, p[1] + r], fill=255)
        img = img.resize((w, lh), Image.BOX)
        px = list(img.tobytes())
        adv = int(round(gw * s + stroke + gap))
        cols = [x for x in range(w) if any(px[y * w + x] >= 20 for y in range(lh))]
        if not cols:
            glyphs.append((adv, 0, 0, []))
            continue
        x0, x1 = cols[0], cols[-1] + 1
        g = [min(15, int(round(15.0 * (px[y * w + x] / 255.0) ** GAMMA))) for y in range(lh) for x in range(x0, x1)]
        glyphs.append((adv, x0 - 1, x1 - x0, g))
    return lh, glyphs


def main(out):
    lines = ["/* generated by tools/gen_rv_font.py: runic strokes, 4 bits per pixel */",
             "#pragma once", "#include <stdint.h>", ""]
    total = 0
    for name, cap, stroke, gap, lh in ROLES:
        h, glyphs = render(cap, stroke, gap, lh)
        data, offs = [], []
        for adv, bx, bw, g in glyphs:
            offs.append(len(data))
            bpr = (bw + 1) // 2
            for y in range(h):
                row = g[y * bw:(y + 1) * bw] + [0]
                for x in range(0, bpr * 2, 2):
                    data.append((row[x] << 4) | row[x + 1])
        total += len(data) + 4 * len(glyphs)
        lines.append(f"static const uint8_t FONT_{name}_DATA[{max(1, len(data))}] = {{")
        for i in range(0, len(data), 24):
            lines.append("    " + ", ".join(f"0x{b:02x}" for b in data[i:i + 24]) + ",")
        lines.append("};")
        lines.append(f"static const uint16_t FONT_{name}_OFF[{len(offs)}] = {{" + ", ".join(map(str, offs)) + "};")
        lines.append(f"static const uint8_t FONT_{name}_ADV[{len(glyphs)}] = {{" + ", ".join(str(a) for a, _, _, _ in glyphs) + "};")
        lines.append(f"static const int8_t FONT_{name}_BX[{len(glyphs)}] = {{" + ", ".join(str(b) for _, b, _, _ in glyphs) + "};")
        lines.append(f"static const uint8_t FONT_{name}_BW[{len(glyphs)}] = {{" + ", ".join(str(w) for _, _, w, _ in glyphs) + "};")
        lines.append(f"static const rv_font_t FONT_{name} = {{ {h}, 32, 95, FONT_{name}_ADV, FONT_{name}_BX, FONT_{name}_BW, FONT_{name}_OFF, FONT_{name}_DATA }};")
        lines.append("")
    print(f"fonts: {total} B")
    Path(out).write_text("\n".join(lines))


if __name__ == "__main__":
    main(sys.argv[1])
