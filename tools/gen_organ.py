"""Ravel's organ pipes for the ORGAN engine: one single cycle per stop family (the spectrum of a
pipe's steady tone, from published descriptions of each family: stopped flutes nearly pure with a
weak twelfth, wide open flutes hollow, principals bright and even, strings rich, reeds brighter
still), each in two band limits (up to 24 and up to 4 harmonics) for high ranks. Made here from
harmonic recipes; no recordings or samples. Writes firmware/app/rv_organ.h."""
import math, pathlib, sys

N = 256
def h(n): return n + 1
STOPS = {
    "FLUTE":     [1.0 if n == 1 else 0.18 if n == 3 else 0.06 if n == 5 else 0.03 if n == 2 else 0.0 for n in range(1, 25)],
    "NACHTHORN": [1.0, 0.22, 0.12, 0.06, 0.04, 0.02] + [0.0] * 18,
    "PRINCIPAL": [1.0 / n ** 0.85 * (1.0 if n < 9 else 0.6) for n in range(1, 25)],
    "GAMBA":     [0.8 / n ** 0.45 for n in range(1, 25)],
    "TRUMPET":   [0.6 / n ** 0.3 * (1.0 + 1.2 * math.exp(-((n - 6) / 3.0) ** 2)) for n in range(1, 25)],
}
CAPS = [24, 4, 1]

def cycle(amps, cap):
    return [sum(a * math.sin(2 * math.pi * (k + 1) * i / N + 0.3 * k) for k, a in enumerate(amps[:cap]) if a) for i in range(N)]

names = list(STOPS)
out = ["/* generated by tools/gen_organ.py: Ravel's organ pipe cycles (from harmonic recipes), 256 signed 8-bit samples,",
       " * full (24 harmonics), plain (4) and pure (the fundamental) */",
       "#ifndef RV_ORG_NAMES", "#define RV_ORG_NAMES", f"#define ORG_STOPS {len(names)}", "#define ORG_N 256",
       "#define ORG_NAMES " + ", ".join(f'"{n}"' for n in names), "#endif",
       "#if defined(ORG_DATA) && !defined(RV_ORG_DATA)", "#define RV_ORG_DATA",
       "static const int8_t org_tab[ORG_STOPS][3][ORG_N] = {"]
for n in names:
    lv = [cycle(STOPS[n], c) for c in CAPS]
    pk = max(abs(x) for w in lv for x in w)
    # every level at the same loudness as the full one, so a rank doesn't jump as it changes level
    rms = lambda w: (sum(x * x for x in w) / len(w)) ** 0.5
    lv = [w if j == 0 else [x * rms(lv[0]) / rms(w) for x in w] for j, w in enumerate(lv)]
    pk = max(abs(x) for w in lv for x in w)
    out.append(f"    {{ /* {n} */")
    for w in lv:
        out.append("        {" + ", ".join(str(int(round(x / pk * 127))) for x in w) + "},")
    out.append("    },")
out += ["};", "#endif"]
dst = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else "firmware/app/rv_organ.h")
dst.write_text("\n".join(out) + "\n")
print(f"organ: {len(names)} stops -> {dst}")
