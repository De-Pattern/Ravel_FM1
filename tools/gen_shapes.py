"""Ravel's envelope shapes (the SHAPE articulation, after the XAOC Zadar's library of complex
envelopes): each is 128 points over the envelope's time, 0..255, plus a hold point (where a GATED
envelope waits while the key is held). Neighbours are chosen so that MORPH between them makes
sense. Writes firmware/app/rv_shapes.h."""
import math, pathlib, sys

N = 128
def ts(): return [i / (N - 1) for i in range(N)]
def env_ad(t, a, d, curve=4.0):
    if t < a: return (t / a) ** 0.6 if a > 0 else 1.0
    u = (t - a) / max(1e-6, 1 - a)
    return math.exp(-curve * u) * (1 - u)
def bump(t, c, w): return math.exp(-((t - c) / w) ** 2)
def hit(t, at, dec):  # a struck shape starting at 'at'
    if t < at: return 0.0
    return math.exp(-(t - at) / dec)

S = []   # (name, function, hold)
S.append(("PLUCK", lambda t: env_ad(t, 0.01, 0.99, 5.0), 0.08))
S.append(("HIT", lambda t: env_ad(t, 0.003, 0.997, 9.0), 0.04))
S.append(("DOUBLE", lambda t: max(hit(t, 0, 0.08), 0.8 * hit(t, 0.35, 0.12)) * (1 - t) ** 0.5, 0.37))
S.append(("TRIPLE", lambda t: max(hit(t, 0, 0.06), 0.75 * hit(t, 0.25, 0.06), 0.55 * hit(t, 0.5, 0.1)) * (1 - t) ** 0.5, 0.51))
S.append(("BOUNCE", lambda t: (lambda k: abs(math.sin(math.pi * k)) * (1 - t) ** 1.5)( (1 - (1 - t) ** 0.45) * 7.5), 0.14))
S.append(("STUTTER", lambda t: (1.0 if (int(t * 8) % 2 == 0) else 0.0) * (1 - 0.7 * t), 0.5))
S.append(("PULSES", lambda t: (1.0 if (t * 4) % 1 < 0.35 else 0.0) if t < 0.99 else 0.0, 0.5))
S.append(("STAIRS UP", lambda t: (math.floor(t * 4.999) + 1) / 5 if t < 0.97 else 0.0, 0.74))
S.append(("STAIRS DN", lambda t: 1 - math.floor(t * 5) / 5, 0.0))
S.append(("RAMP UP", lambda t: t ** 1.2 if t < 0.97 else (1 - (t - 0.97) / 0.03), 0.6))
S.append(("REVERSE", lambda t: (math.exp(5 * t) - 1) / (math.exp(5) - 1) if t < 0.97 else (1 - (t - 0.97) / 0.03), 0.6))
S.append(("SWELL", lambda t: math.sin(math.pi * t) ** 2, 0.5))
S.append(("HUMP", lambda t: bump(t, 0.3, 0.18) * (t < 0.95 or 1) * (1 - t) ** 0.3, 0.3))
S.append(("TWIN HUMP", lambda t: max(bump(t, 0.25, 0.12), 0.85 * bump(t, 0.68, 0.14)) * (1 - t) ** 0.3, 0.25))
S.append(("SWELL HIT", lambda t: (t / 0.7) ** 3 if t < 0.7 else math.exp(-(t - 0.7) * 14), 0.69))
S.append(("ADSR", lambda t: (t / 0.05) if t < 0.05 else (1 - 0.4 * (1 - math.exp(-(t - 0.05) * 12))) if t < 0.7 else 0.6 * math.exp(-(t - 0.7) * 12) * (1 - (t - 0.7) / 0.3), 0.45))
S.append(("ORGAN", lambda t: min(1.0, t / 0.02) if t < 0.94 else (1 - (t - 0.94) / 0.06), 0.5))
S.append(("TREMOLO", lambda t: min(1, t / 0.04) * (0.6 + 0.4 * math.cos(2 * math.pi * 6 * t)) * (1 - t ** 4), 0.5))
S.append(("WOBBLE", lambda t: min(1, t / 0.1) * (0.55 + 0.45 * math.sin(2 * math.pi * 2.5 * t)) * (1 - t ** 3), 0.5))
S.append(("FLUTTER", lambda t: env_ad(t, 0.02, 0.98, 2.5) * (0.5 + 0.5 * abs(math.sin(2 * math.pi * (5 * t + 3 * t * t)))), 0.15))
S.append(("SAW BURST", lambda t: (1 - (t * 5) % 1) * (1 - t) if t < 0.999 else 0.0, 0.2))
S.append(("SPIKES", lambda t: ((t * 6) % 1) ** 8 * (0.3 + 0.7 * t) * (1 if t < 0.99 else 0), 0.83))
S.append(("DRIP", lambda t: max(hit(t, 0.0, 0.03), 0.5 * hit(t, 0.3, 0.03), 0.35 * hit(t, 0.55, 0.03), 0.25 * hit(t, 0.8, 0.03)), 0.02))
S.append(("BREATH", lambda t: math.sin(math.pi * t) ** 1.5 * (0.85 + 0.15 * math.sin(2 * math.pi * 9 * t)), 0.5))

def clamp(x): return max(0.0, min(1.0, x))
out = ["/* generated by tools/gen_shapes.py: Ravel's envelope shapes, 128 points each (0..255) */",
       "#ifndef RV_SHP_NAMES",
       "#define RV_SHP_NAMES",
       f"#define SHP_N {len(S)}",
       f"#define SHP_LEN {N}",
       "#define SHP_NAMES " + ", ".join(f'"{n}"' for n, _, _ in S),
       "#endif",
       "#if defined(SHP_DATA) && !defined(RV_SHP_DATA)   /* the tables: only the synth and the screen need them */",
       "#define RV_SHP_DATA",
       "static const uint8_t shp_hold[SHP_N] = {" + ", ".join(str(int(round(h * (N - 1)))) for _, _, h in S) + "};",
       "static const uint8_t shp_tab[SHP_N][SHP_LEN] = {"]
for name, f, _ in S:
    v = [clamp(f(t)) for t in ts()]
    v[-1] = 0.0                                  # every shape ends at rest
    out.append("    {" + ", ".join(str(int(round(x * 255))) for x in v) + "},   /* " + name + " */")
out += ["};", "#endif"]
dst = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else "firmware/app/rv_shapes.h")
dst.write_text("\n".join(out) + "\n")
print(f"shapes: {len(S)} -> {dst}")
