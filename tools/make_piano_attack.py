"""PIANO's sampled attack: firmware/app/rv_pnatk.h from a recording of a grand's note, the first 25 ms of its
hammer strike above the strings' low partials (high-passed at 1.5 kHz), faded out, as 8-bit at 22,050 Hz. The PIANO
engine lays it over its modelled strings at each note (ATTACK), the bite and knock of a real hammer on steel.

The table in the repository was made from the Salamander Grand Piano V3 (Alexander Holm, CC-BY 3.0,
https://archive.org/details/SalamanderGrandPianoV3): F#4, velocity layer 12, at 22,050 Hz.
Run: tools/make_piano_attack.py NOTE.wav   (any rate; mono or stereo; needs numpy and scipy)"""
import sys
import numpy as np
from scipy.io import wavfile
from scipy.signal import butter, sosfiltfilt, resample_poly

SR, MS, HP = 22050, 25, 1500.0
sr, x = wavfile.read(sys.argv[1])
x = x.astype(np.float64)
if x.ndim > 1:
    x = x.mean(axis=1)
if sr != SR:
    x = resample_poly(x, SR, sr)
x = sosfiltfilt(butter(4, HP / (SR / 2), "hp", output="sos"), x)
head = np.abs(x[:SR // 2])
on = int(np.argmax(head > head.max() * 0.05))    # (the strike: in the first half second)
n = SR * MS // 1000
seg = x[max(0, on - 8):max(0, on - 8) + n]
seg = seg * np.minimum(1.0, np.linspace(1.6, 0.0, len(seg)))      # (full at first, faded to nothing at 25 ms)
seg = seg * np.minimum(1.0, np.arange(len(seg)) / 4.0)            # (no click at its start)
seg = np.round(seg / np.abs(seg).max() * 127).astype(int)
rows = ",\n".join(", ".join(str(v) for v in seg[i:i + 24]) for i in range(0, len(seg), 24))
out = ("/* generated by tools/make_piano_attack.py: PIANO's sampled attack, the hammer strike of a grand's F#4 above\n"
       " * 1.5 kHz, 25 ms at 22,050 Hz, 8-bit. From the Salamander Grand Piano V3 (Alexander Holm, CC-BY 3.0). */\n"
       "#pragma once\n#include <stdint.h>\n"
       f"#define PN_ATK_N {len(seg)}\n"
       "static const int8_t pn_atk[PN_ATK_N] = {\n" + rows + "\n};\n")
open("firmware/app/rv_pnatk.h", "w").write(out)
print(f"rv_pnatk.h: {len(seg)} samples")
