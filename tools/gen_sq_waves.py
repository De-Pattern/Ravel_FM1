"""Ravel's SQ waves: original 8-bit single cycles in the families of the Ensoniq SQ-80's waves
(saw, bell, piano, voices, formants, organ, reed, digital...), made here from harmonic recipes,
not taken from any ROM. Writes firmware/app/rv_sqwaves.h: 256 signed 8-bit samples per wave."""
import math, random, sys, pathlib

N = 256

def additive(amps, phases=None):
    out = []
    for i in range(N):
        x = 2 * math.pi * i / N
        out.append(sum(a * math.sin((h + 1) * x + (phases[h] if phases else 0.0)) for h, a in enumerate(amps) if a))
    return out

def formant(center, width, count=40, tilt=1.0):
    return [math.exp(-((h + 1 - center) / width) ** 2) / ((h + 1) ** (tilt * 0.3)) for h in range(count)]

rnd = random.Random(80)
W = {}
W["SAW"] = additive([1.0 / h for h in range(1, 48)])
W["SQUARE"] = additive([1.0 / h if h % 2 else 0 for h in range(1, 48)])
W["PULSE"] = additive([math.sin(math.pi * h * 0.25) / h for h in range(1, 48)])
W["SINE"] = additive([1.0])
W["TRI"] = additive([((-1) ** ((h - 1) // 2)) / h ** 2 if h % 2 else 0 for h in range(1, 32)])
W["BELL"] = additive([1.0 if h == 1 else 0.7 if h == 3 else 0.55 if h == 5 else 0.5 if h == 7 else 0.35 if h == 11
                      else 0.25 if h == 13 else 0.12 if h == 17 else 0 for h in range(1, 20)])
W["BASS"] = additive([1.0, 0.8, 0.45, 0.3, 0.15, 0.1, 0.05])
W["PIANO"] = additive([(0.0 if h % 7 == 0 else 1.0) / h ** 1.3 for h in range(1, 40)])
W["EPIANO"] = additive([1.0, 0.18, 0.05] + [0] * 10 + [0.12, 0.06])
W["VOICE1"] = additive([v + (0.6 if h == 0 else 0) for h, v in enumerate(formant(6.5, 1.8))])        # an "ah"
W["VOICE2"] = additive([v + (0.7 if h == 0 else 0) for h, v in enumerate(formant(3.5, 1.2))])        # an "oh"
W["ORGAN"] = additive([1.0 if h in (1, 2, 4, 8) else 0.6 if h in (3, 6) else 0 for h in range(1, 12)])
W["REED"] = additive([1.0 / h ** 0.7 if h % 2 else 0.25 / h for h in range(1, 40)])
W["SYNTH1"] = [a + 0.6 * b for a, b in zip(W["SAW"], additive([math.sin(math.pi * h * 0.1) / h for h in range(1, 48)]))]
W["SYNTH2"] = additive([1.0 / h ** 0.8 for h in range(1, 40)], [rnd.uniform(0, 2 * math.pi) for _ in range(40)])
W["FORMT1"] = additive(formant(6, 1.5))
W["FORMT2"] = additive(formant(10, 2.0))
W["FORMT3"] = additive(formant(16, 2.5))
W["OCTAVE"] = additive([1.0, 0.9, 0, 0.7, 0, 0, 0, 0.5])
W["DIGIT"] = [float(((i ^ (i >> 3)) * 37) & 255) - 128.0 for i in range(N)]                          # bit logic: crunchy
W["GLINT"] = additive([0.4 if h < 2 else 1.0 / (1 + abs(h - 24)) for h in range(1, 48)])
W["SPIKE"] = additive([1.0 for h in range(1, 48)])

names = list(W)
# band-limited copies for the clean end of GRIT: level 0 is the raw cycle (it aliases like the
# DOC chip did), levels 1-4 keep at most 32, 16, 8, 4 harmonics
CAPS = [128, 32, 16, 8, 4]

def dft(w):
    h = []
    for k in range(1, N // 2):
        re_ = sum(w[i] * math.cos(2 * math.pi * k * i / N) for i in range(N)) * 2 / N
        im_ = sum(w[i] * math.sin(2 * math.pi * k * i / N) for i in range(N)) * 2 / N
        h.append((re_, im_))
    return h

def rebuild(h, cap):
    return [sum(re_ * math.cos(2 * math.pi * (k + 1) * i / N) + im_ * math.sin(2 * math.pi * (k + 1) * i / N)
                for k, (re_, im_) in enumerate(h[:cap])) for i in range(N)]

out = ["/* generated by tools/gen_sq_waves.py: Ravel's own SQ-family waves (made from harmonic recipes,",
       " * not from any ROM), 256 signed 8-bit samples each, raw and at four band limits */",
       "#ifndef RV_SQ_NAMES",
       "#define RV_SQ_NAMES",
       f"#define SQ_NWAVES {len(names)}",
       f"#define SQ_NMIPS {len(CAPS)}",
       "#define SQ_WAVE_NAMES " + ", ".join(f'"{n}"' for n in names),
       "#endif",
       "#if defined(SQ_WAVE_DATA) && !defined(RV_SQ_DATA)   /* the tables: only the synth needs them */",
       "#define RV_SQ_DATA",
       "static const uint8_t sq_mip_caps[SQ_NMIPS] = {" + ", ".join(map(str, CAPS)) + "};",
       "static const int8_t sq_waves[SQ_NWAVES][SQ_NMIPS][256] = {"]
for n in names:
    w = W[n]
    m = sum(w) / N
    w = [v - m for v in w]
    h = dft(w)
    levels = [w] + [rebuild(h, c) for c in CAPS[1:]]
    peak = max(abs(v) for lv in levels for v in lv) or 1.0
    out.append("    { /* " + n + " */")
    for lv in levels:
        out.append("        {" + ", ".join(str(max(-127, min(127, int(round(v / peak * 127))))) for v in lv) + "},")
    out.append("    },")
out.append("};")
out.append("#endif")
dst = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else "firmware/app/rv_sqwaves.h")
dst.write_text("\n".join(out) + "\n")
print(f"sq waves: {len(names)} x {len(CAPS)} -> {dst}")
