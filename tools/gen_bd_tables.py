#!/usr/bin/env python3
"""Generate the lookup tables for the fixed-point Beads port (core/beads/bd_tables.c).

Usage: tools/gen_bd_tables.py <path to eurorack/beads/dsp/mu_law.cc> > core/beads/bd_tables.c

The mu-law decode table is read from Beads' own source so the port decodes the
tape exactly as Beads does. Everything else is computed here.
"""
import math
import re
import sys

def emit(name, ctype, values, per_line=8):
    print(f"const {ctype} {name}[{len(values)}] = {{")
    for i in range(0, len(values), per_line):
        print("  " + ", ".join(str(v) for v in values[i:i + per_line]) + ",")
    print("};\n")

def main():
    src = open(sys.argv[1]).read()
    body = src[src.index("lut_ulaw_f[256]"):]
    body = body[body.index("{") + 1:body.index("}")]
    ulaw = [float(x.rstrip("f")) for x in re.findall(r"-?\d+\.\d+f", body)]
    assert len(ulaw) == 256, len(ulaw)

    print("/* Generated by tools/gen_bd_tables.py. Do not edit. */")
    print('#include "bd_tables.h"\n')

    # 2^(i/256) for i = 0..256, Q30.
    emit("bd_lut_exp2_q30", "uint32_t", [round(2 ** (i / 256) * (1 << 30)) for i in range(257)])

    # Soft clip: x (27 + x^2) / (27 + 9 x^2) for x = 0..3 in 512 steps, Q15.
    vals = []
    for i in range(513):
        x = 3.0 * i / 512
        vals.append(round(x * (27 + x * x) / (27 + 9 * x * x) * 32768))
    emit("bd_lut_softclip_q15", "int32_t", vals)

    # Mu-law decode, Q15, from Beads' table.
    emit("bd_lut_ulaw_q15", "int16_t", [max(-32768, min(32767, round(v * 32768))) for v in ulaw])

    # Sine, as Beads' lut_sine (1024 + 256 + 1 points), Q15.
    n = 1024
    emit("bd_lut_sine_q15", "int16_t",
         [max(-32767, min(32767, round(math.sin(2 * math.pi * i / n) * 32767))) for i in range(n + n // 4 + 1)])

    # 1 / sqrt(n) for n = 0..64, Q15 (n = 0 unused).
    emit("bd_lut_inv_sqrt_q15", "int32_t", [32768] + [round(32768 / math.sqrt(k)) for k in range(1, 65)])

if __name__ == "__main__":
    main()
